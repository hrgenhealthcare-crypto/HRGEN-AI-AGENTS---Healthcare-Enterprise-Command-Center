export const AGENT_PORTRAITS: Record<string, string> = Object.fromEntries(
  Object.entries(AGENT_PORTRAIT_SPECS).map(([id, spec]) => [id, buildPortraitSvgDataUri(spec)])
);

export function getAgentPortraitSpec(podId?: string, agentName?: string): AgentPortraitSpec {
  if (podId && AGENT_PORTRAIT_SPECS[podId]) {
    return AGENT_PORTRAIT_SPECS[podId];
  }
  if (agentName) {
    const lower = agentName.toLowerCase();
    const matched = Object.values(AGENT_PORTRAIT_SPECS).find(
      (s) => lower.includes(s.name.toLowerCase().split(' ')[0]) || s.name.toLowerCase().includes(lower)
    );
    if (matched) return matched;
  }
  return AGENT_PORTRAIT_SPECS['pod-01'];
}

export function getAgentPortraitUrl(podId?: string, agentName?: string): string {
  const spec = getAgentPortraitSpec(podId, agentName);
  return AGENT_PORTRAITS[spec.id] || AGENT_PORTRAITS['pod-01'];
}


export interface AgentPortraitCompat {
  podId: string;
  accentColor: string;
  secondaryColor: string;
  portraitSvg: string;
}

export function getAgentPortrait(podId: string): AgentPortraitCompat {
  const spec = getAgentPortraitSpec(podId);
  return {
    podId: spec.id,
    accentColor: spec.accent,
    secondaryColor: spec.accentSoft,
    portraitSvg: getAgentPortraitUrl(podId),
  };
}
